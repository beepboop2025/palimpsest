def canonical_json(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def _e(value: Any) -> str:
    return html.escape(str(value), quote=True)


def _status_label(value: str) -> str:
    return value.replace("_", " ")


def _status_badge(value: str) -> str:
    safe = re.sub(r"[^a-z0-9-]", "-", value.lower().replace("_", "-"))
    return f'<span class="cn-status cn-status--{safe}">{_e(_status_label(value))}</span>'


def _fmt_value(value: Any) -> str:
    if value is None:
        return "not available"
    if isinstance(value, float):
        return f"{value:,.6f}".rstrip("0").rstrip(".")
    return str(value)


def _local_nav(route: str) -> str:
    links = (
        ("/china/", "Current read"),
        ("/china/sources/", "Source ledger"),
        ("/china/releases/", "Release docket"),
        ("/china/domains/", "Coverage domains"),
        ("/readings/china-index-latest.json", "Machine index"),
    )
    parts = ['<nav class="cn-local" aria-label="China Observatory">']
    for href, label in links:
        current = ""
        if route == href:
            current = ' aria-current="page"'
        elif href != "/china/" and route.startswith(href):
            current = ' aria-current="location"'
        parts.append(f'<a href="{href}"{current}>{label}</a>')
    parts.append("</nav>")
    return "".join(parts)


def _breadcrumbs(items: Sequence[tuple[str, str]]) -> str:
    parts = ['<nav class="cn-crumbs" aria-label="Breadcrumb"><ol>']
    for index, (label, href) in enumerate(items):
        if index == len(items) - 1:
            parts.append(f'<li aria-current="page">{_e(label)}</li>')
        else:
            parts.append(f'<li><a href="{_e(href)}">{_e(label)}</a></li>')
    parts.append("</ol></nav>")
    return "".join(parts)



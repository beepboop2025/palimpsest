#!/usr/bin/env python3
"""Build the static, evidence-bound China Observatory surface.

The build is deliberately offline.  It accepts four public evidence inputs
plus a presentation config, validates their joins, and writes a compact
machine index and server-rendered pages.  It never upgrades a registry status
because a related release happened to appear in the pulse.
"""

    assert page.count("cn-loom__cell--gap") > 0
    assert '<div class="cn-loom-wrap" role="region" tabindex="0"' in page
    assert '<table class="cn-loom">' in page
    assert page.count('<th class="cn-loom__label" scope="row">') == 4
    assert 'role="cell"' not in page
    assert "No metric is an estimate of true GDP." in page
    assert "Backtests published; forecasts withheld" in page
    assert "0 / 3" in page
    assert page.count('class="cn-forecast-target"') == 3
    assert page.count("No forecast is published.") == 3
    assert "/readings/china-econ-forecast-latest.json" in page



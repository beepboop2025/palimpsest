from __future__ import annotations

import json
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
CHINA = ROOT / "china"


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.hrefs: list[str] = []
        self.ids: list[str] = []
        self.canonicals: list[str] = []
        self.stylesheets: list[str] = []
        self.scripts: list[dict[str, str | None]] = []
        self._json_ld_depth = 0
        self._json_ld_parts: list[str] = []
        self.json_ld: list[dict] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = dict(attrs)
        if values.get("id"):
            self.ids.append(str(values["id"]))
        if tag == "a" and values.get("href"):
            self.hrefs.append(str(values["href"]))
        if tag == "link" and values.get("rel") == "canonical" and values.get("href"):
            self.canonicals.append(str(values["href"]))
        if tag == "link" and values.get("rel") == "stylesheet" and values.get("href"):
            self.stylesheets.append(str(values["href"]))
        if tag == "script":
            self.scripts.append(values)
            if values.get("type") == "application/ld+json":
                self._json_ld_depth += 1

    def handle_endtag(self, tag: str) -> None:
        if tag == "script" and self._json_ld_depth:
            self._json_ld_depth -= 1
            raw = "".join(self._json_ld_parts)
            self._json_ld_parts = []
            self.json_ld.append(json.loads(raw))

    def handle_data(self, data: str) -> None:
        if self._json_ld_depth:
            self._json_ld_parts.append(data)


def _html_pages() -> list[Path]:
    return sorted(CHINA.rglob("*.html"))


def _parser(path: Path) -> PageParser:
    parser = PageParser()
    parser.feed(path.read_text(encoding="utf-8"))
    return parser


def _route_to_path(href: str) -> Path:
    route = urlsplit(href).path
    assert route.startswith("/china/")
    relative = route.lstrip("/")
    if route.endswith("/"):
        relative += "index.html"
    return ROOT / relative


def test_exact_static_route_inventory_is_server_rendered():
    pages = _html_pages()
    assert len(pages) == 56
    assert len(list((CHINA / "sources").glob("*/index.html"))) == 33
    assert len(list((CHINA / "releases").glob("*/index.html"))) == 7
    assert len(list((CHINA / "domains").glob("*/index.html"))) == 12
    assert (CHINA / "index.html") in pages
    assert (CHINA / "sources" / "index.html") in pages
    assert (CHINA / "releases" / "index.html") in pages
    assert (CHINA / "domains" / "index.html") in pages


def test_every_page_has_compact_versioned_head_real_nav_and_unique_ids():
    for path in _html_pages():
        page = path.read_text(encoding="utf-8")
        parsed = _parser(path)
        assert page.startswith("<!doctype html>")
        assert '<meta name="palimpsest:schema-version" content="palimpsest-china-index.v1">' in page
        assert '<nav class="ps-nav" aria-label="Primary">' in page
        assert '<nav class="cn-local" aria-label="China Observatory">' in page
        assert '<main id="main" class="cn-main">' in page
        assert '<link rel="stylesheet" href="/assets/china.css">' in page
        assert '<script src="/assets/china.js" defer></script>' in page
        assert "<!-- GENERATED BY scripts/build_china_site.py -->" in page
        assert len(parsed.canonicals) == 1
        assert parsed.canonicals[0].startswith("https://palimpsest.info/china/")
        assert len(parsed.ids) == len(set(parsed.ids)), path
        assert len(parsed.json_ld) == 1
        assert parsed.json_ld[0]["url"] == parsed.canonicals[0]


def test_every_internal_china_link_resolves_to_an_ssr_page():
    broken: list[tuple[str, str]] = []
    for path in _html_pages():
        for href in _parser(path).hrefs:
            if not urlsplit(href).path.startswith("/china/"):
                continue
            target = _route_to_path(href)
            if not target.is_file():
                broken.append((str(path.relative_to(ROOT)), href))
    assert broken == []



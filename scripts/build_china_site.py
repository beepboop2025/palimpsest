def _sitemap(html_paths: Sequence[Path], index: Mapping[str, Any]) -> bytes:
    modified = str(index["head"]["generated_at"])[:10]
    urls = []
    for path in sorted(html_paths, key=str):
        relative = path.relative_to(ROOT)
        route = "/" + str(relative).replace(os.sep, "/")
        if route.endswith("index.html"):
            route = route[: -len("index.html")]
        urls.append(
            f"  <url><loc>{_e('https://palimpsest.info' + route)}</loc><lastmod>{_e(modified)}</lastmod></url>"
        )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!-- GENERATED BY scripts/build_china_site.py -->\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    ).encode("utf-8")


def build_outputs(*, root: Path = ROOT) -> dict[Path, bytes]:
    index = build_index(root=root)
    outputs: dict[Path, bytes] = {
        root / "readings" / "china-index-latest.json": canonical_json(index),
        root / "china" / "index.html": _home(index),
        root / "china" / "sources" / "index.html": _sources_index(index),
        root / "china" / "releases" / "index.html": _releases_index(index),
        root / "china" / "domains" / "index.html": _domains_index(index),
    }
    for source in index["sources"]:
        outputs[root / "china" / "sources" / source["source_id"] / "index.html"] = _source_detail(source, index)
    for release in index["releases"]:
        outputs[root / "china" / "releases" / release["metric_id"] / "index.html"] = _release_detail(release, index)
    for domain in index["domains"]:
        outputs[root / "china" / "domains" / domain["domain"] / "index.html"] = _domain_detail(domain, index)

    html_paths = [path for path in outputs if path.suffix == ".html"]
    sitemap_path = root / "china" / "sitemap.xml"
    outputs[sitemap_path] = _sitemap(html_paths, index)
    manifest_path = root / "china" / "generated-manifest.json"
    manifest_outputs = sorted(
        str(path.relative_to(root)).replace(os.sep, "/")
        for path in [*outputs, manifest_path]
    )
    output_sha256 = {
        str(path.relative_to(root)).replace(os.sep, "/"): _sha256(payload)
        for path, payload in sorted(outputs.items(), key=lambda item: str(item[0]))
    }
    outputs[manifest_path] = canonical_json(
        {
            "schema_version": MANIFEST_SCHEMA,
            "generated_at": index["head"]["generated_at"],
            "generator": "scripts/build_china_site.py",
            "outputs": manifest_outputs,
            "output_sha256": output_sha256,
        }
    )
    return outputs


def _atomic_write(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fchmod(handle.fileno(), 0o644)
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        directory_fd = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass


def _managed_extras(outputs: Mapping[Path, bytes], *, root: Path) -> list[Path]:
    expected = set(outputs)
    extras: list[Path] = []
    for collection in ("sources", "releases", "domains"):
        collection_root = root / "china" / collection
        if not collection_root.exists():
            continue
        for candidate in collection_root.glob("*/index.html"):
            if candidate in expected:
                continue
            try:
                prefix = candidate.read_bytes()[:4096]
            except OSError as exc:
                raise ChinaSiteError(f"cannot inspect managed candidate {candidate}: {exc}") from exc
            if GENERATED_MARKER.encode() in prefix:
                extras.append(candidate)
    return sorted(extras)


def check(outputs: Mapping[Path, bytes], *, root: Path = ROOT) -> list[str]:
    drift: list[str] = []
    for path, expected in sorted(outputs.items(), key=lambda item: str(item[0])):
        try:
            current = path.read_bytes()
        except FileNotFoundError:
            drift.append(f"missing {path.relative_to(root)}")
            continue
        if current != expected:
            drift.append(f"stale {path.relative_to(root)}")
    for path in _managed_extras(outputs, root=root):
        drift.append(f"extra {path.relative_to(root)}")
    return drift


def publish(outputs: Mapping[Path, bytes], *, root: Path = ROOT) -> tuple[int, int, int]:
    changed = 0
    unchanged = 0
    manifest_path = root / "china" / "generated-manifest.json"
    if manifest_path not in outputs:
        raise ChinaSiteError("generated output set is missing the publication manifest")

    # The manifest is the commit marker for this multi-file static publication.
    # Write all content, retire only marker-owned stale details, then replace the
    # manifest last so consumers never see a manifest for a partial build.
    content_outputs = [
        item for item in sorted(outputs.items(), key=lambda item: str(item[0]))
        if item[0] != manifest_path
    ]
    for path, payload in content_outputs:
        try:
            current = path.read_bytes()
        except FileNotFoundError:
            current = None
        if current == payload:
            unchanged += 1
            continue
        _atomic_write(path, payload)
        changed += 1
    removed = 0
    for extra in _managed_extras(outputs, root=root):
        extra.unlink()
        removed += 1
        try:
            extra.parent.rmdir()
        except OSError:
            pass

    manifest_payload = outputs[manifest_path]
    try:
        current_manifest = manifest_path.read_bytes()
    except FileNotFoundError:
        current_manifest = None
    if current_manifest == manifest_payload:
        unchanged += 1
    else:
        _atomic_write(manifest_path, manifest_payload)
        changed += 1
    return changed, unchanged, removed


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(list(argv) if argv is not None else None)
    try:
        outputs = build_outputs()
        if args.check:
            drift = check(outputs)
            for item in drift:
                print(item)
            if drift:
                print(f"China Observatory drift: {len(drift)} file(s)")
                return 1
            print(f"China Observatory current: {len(outputs)} files")
            return 0
        changed, unchanged, removed = publish(outputs)
    except ChinaSiteError as exc:
        parser.error(str(exc))
    print(
        f"China Observatory -> china/ · {len(outputs)} files · "
        f"{changed} updated · {unchanged} unchanged · {removed} retired"
    )
    return 0


